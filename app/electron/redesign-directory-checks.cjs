const assert = require('node:assert/strict')

module.exports = async function checkDirectory({ evaluate, wait, clickText, saved, linkedDirectory, fs, path, setDeleteFailure }) {
  const target = await saved(state => state.cases.find(item => item.name === '新版回归测试案件').id)
  await evaluate("Object.defineProperty(document, 'visibilityState', { configurable: true, get: () => 'visible' }); true")
  const focus = () => evaluate("window.dispatchEvent(new Event('focus'))")
  const hasEvidence = name => saved(state => state.evidences.some(item => item.caseId === target && item.fileName === name && item.storageKey))
  const openDirectory = async () => {
    await clickText('.add-mat', '本地文件夹联动')
    await wait("document.querySelector('.new-directory') && !document.querySelector('.new-directory button:disabled')")
  }
  const sync = () => clickText('.new-directory button', '立即同步')
  const poll = async predicate => {
    const deadline = Date.now() + 20000
    while (Date.now() < deadline) {
      if (await predicate()) return
      await new Promise(resolve => setTimeout(resolve, 500))
    }
    throw new Error('文件夹联动持久化检查超时')
  }
  fs.writeFileSync(path.join(linkedDirectory, '新增材料.txt'), '新增材料第一版')
  await focus()
  await evaluate("document.dispatchEvent(new Event('visibilitychange'))")
  await openDirectory()
  await new Promise(resolve => setTimeout(resolve, 1500))
  assert.equal(await hasEvidence('新增材料.txt'), false, '返回窗口或打开目录管理不应自动导入材料')
  await sync()
  await poll(() => hasEvidence('新增材料.txt'))
  await wait("document.querySelector('.pane-l')?.textContent.includes('新增材料.txt')")
  const original = await saved(state => state.evidences.find(item => item.caseId === target && item.fileName === '新增材料.txt'))
  fs.writeFileSync(path.join(linkedDirectory, '新增材料.txt'), '新增材料第二版，补充修改后的正文')
  await wait("!document.querySelector('.new-directory button:disabled')")
  await sync()
  await poll(() => saved(state => state.evidences.some(item => item.id === original.id && item.sourceFingerprint !== original.sourceFingerprint && item.contentHash !== original.contentHash)))
  fs.unlinkSync(path.join(linkedDirectory, '新增材料.txt'))
  await wait("!document.querySelector('.new-directory button:disabled')")
  await sync()
  await poll(async () => !await hasEvidence('新增材料.txt'))
  await wait("!document.querySelector('.new-directory button:disabled')")
  await clickText('.new-directory button', '完成')
  await clickText('.topbar button', '首页')
  await wait("document.querySelector('#pg-home') && document.querySelector('.dock .dock-ava')")
  await evaluate("document.querySelector('.dock-ava').click()")
  await wait("document.querySelector('.acct-grid')")
  await clickText('[role=tab]', '案件库')
  await wait("document.querySelector('.lrow')")
  setDeleteFailure(target)
  await evaluate("Array.from(document.querySelectorAll('.lrow')).find(row=>row.textContent.includes('新版回归测试案件')).querySelector('.bye').click()")
  await clickText('.fm-ft button', '确认删除')
  await wait("document.querySelector('.new-error')?.textContent.includes('测试删除失败')")
  setDeleteFailure(null)
  await saved(state => assert.ok(state.cases.some(item => item.id === target)))
  const config = JSON.parse(fs.readFileSync(path.join(linkedDirectory, '..', 'electron-profile', 'case-directories.json'), 'utf8'))
  assert.ok(Object.values(config).some(items => items.some(item => item.path === linkedDirectory)), '删除案件失败后应保留本机目录链接')
  await clickText('.fm-ft button', '取消')
  await clickText('.new-error button', '关闭')
  await evaluate("Array.from(document.querySelectorAll('.lrow')).find(row=>row.textContent.includes('新版回归测试案件')).querySelector('.op.pri').click()")
  await wait("document.querySelector('#pg-ws')")
  fs.writeFileSync(path.join(linkedDirectory, '删除失败后新增.txt'), '失败恢复后仍能同步')
  await openDirectory()
  await sync()
  await poll(() => hasEvidence('删除失败后新增.txt'))
  await wait("!document.querySelector('.new-directory button:disabled')")
  await clickText('.new-directory button', '解除链接')
  await wait("document.querySelector('.directory-confirm')")
  await clickText('.directory-confirm button', '取消解除')
  assert.equal(await hasEvidence('测试材料.txt'), true)
  await clickText('.new-directory button', '解除链接')
  await clickText('.directory-confirm button', '确认解除并清除记录')
  await wait("document.querySelector('.directory-list')?.textContent.includes('尚未链接') && !document.querySelector('.directory-confirm')")
  await saved(state => {
    assert.equal(state.evidences.filter(item => item.caseId === target && item.directoryId).length, 0)
    assert.ok(state.certificates.some(item => item.caseId === target))
  })
  assert.ok(fs.existsSync(path.join(linkedDirectory, '测试材料.txt')))
  await focus()
  await new Promise(resolve => setTimeout(resolve, 350))
  assert.equal(await hasEvidence('测试材料.txt'), false)
  await clickText('.new-directory button', '完成')
  await evaluate("delete document.visibilityState")
  console.log('PASS directory linking, manual-only sync, modify, delete and unlink')
}
