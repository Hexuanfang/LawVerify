const assert = require('node:assert/strict')

module.exports = async function checkDocumentAI({ evaluate, wait, clickText, fill, screenshot, saved, writeWorkspace, reload, enter, documentMock, billingLog, window, setBillingDelay }) {
  await saved(async state => { state.aiBillingMode = 'client'; await writeWorkspace(state) })
  await reload()
  const caseName = await saved(state => state.cases.find(item => item.id === 'qa-case').name)
  await enter(caseName)
  await clickText('.workbench-assistant-tabs [role=tab]', '起草与改写')
  await wait("document.querySelector('.document-assistant')")
  await clickText('.document-assistant button', '语音')
  await wait("document.querySelector('.document-assistant [role=alert]')?.textContent.includes('语音输入尚未启用')")
  await wait("!document.querySelector('.document-evidence-actions button').disabled")
  await clickText('.document-evidence-actions button', '清空')
  assert.equal(await evaluate("Array.from(document.querySelectorAll('.document-assistant-actions button')).find(item=>item.textContent==='开始起草').disabled"), true)
  await clickText('.document-evidence-actions button', '全选')
  await evaluate("document.querySelector('[aria-label=文书生成模型]').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,pointerType:'mouse'}))")
  await wait("document.querySelector('[role=option]')")
  await clickText('[role=option]', '回归模型')
  await fill('#document-ai-prompt', '起草民事起诉状')
  documentMock.setScenario('success')
  const startCharges = billingLog.filter(item => item.type === 'charge').length
  await clickText('.document-assistant-actions button', '开始起草')
  await wait("document.querySelector('.doc-paper')?.textContent.includes('AI起草正文') && !document.querySelector('.document-assistant-actions button')?.disabled")
  assert.deepEqual(documentMock.requests.at(-1).payload.evidenceIds, ['qa-evidence'])
  assert.equal(documentMock.requests.at(-1).payload.model, 'qa-model')
  assert.equal(billingLog.filter(item => item.type === 'charge').length, startCharges + 1)
  await clickText('.document-assistant-mode button', '改写当前文书')
  await wait("document.querySelector('.whole-document-content[contenteditable=true]')")
  await evaluate("document.querySelector('.whole-document-content').focus();document.execCommand('selectAll');true")
  await window.webContents.insertText('改写前手动修改的正文。')
  await fill('#document-ai-prompt', '补充论证并优化表达')
  await clickText('.document-assistant-actions button', '开始改写')
  await wait("document.querySelector('.doc-paper')?.textContent.includes('已按要求修改后的正文')")
  assert.match(documentMock.requests.at(-1).original.paragraphs.map(item => item.text).join(''), /改写前手动修改的正文/)
  await screenshot('document-ai')
  documentMock.setScenario('interrupt')
  await fill('#document-ai-prompt', '再次调整表述')
  await clickText('.document-assistant-actions button', '开始改写')
  await wait("document.querySelector('.document-generated-preview')?.textContent.includes('中断前已经生成')")
  assert.equal(await evaluate("Array.from(document.querySelectorAll('.workbench-assistant-tabs [role=tab]')).every(button=>button.disabled)"), true)
  await evaluate("document.querySelector('.doc-paper .mk')?.click(); true")
  await evaluate("new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))")
  assert.ok(await evaluate("Boolean(document.querySelector('.document-assistant'))"), '生成期间点击正文高亮应保持助手挂载')
  await clickText('.document-assistant-actions button', '停止生成')
  await wait("document.querySelector('.document-assistant [role=status]')?.textContent.includes('中断草稿')")
  await saved(state => assert.ok(state.certificates.some(item => item.caseId === 'qa-case' && item.title.includes('中断草稿') && item.paragraphs.some(paragraph => paragraph.text.includes('中断前已经生成')))))
  assert.ok(billingLog.some(item => item.type === 'refund'))
  documentMock.setScenario('failure')
  await fill('#document-ai-prompt', '失败回归')
  const refunds = billingLog.filter(item => item.type === 'refund').length
  await clickText('.document-assistant-actions button', '开始改写')
  await wait("document.querySelector('.new-error')?.textContent.includes('模拟模型生成失败')")
  assert.equal(billingLog.filter(item => item.type === 'refund').length, refunds + 1)
  await clickText('.new-error button', '关闭')
  documentMock.setScenario('success')
  const requestCount = documentMock.requests.length
  const chargeCount = billingLog.filter(item => item.type === 'charge').length
  const originalToken = await evaluate("localStorage.getItem('lawverify-cloud-token')")
  setBillingDelay(600)
  try {
    await fill('#document-ai-prompt', '扣费期间会话变化回归')
    await clickText('.document-assistant-actions button', '开始改写')
    const deadline = Date.now() + 10000
    while (billingLog.filter(item => item.type === 'charge').length === chargeCount && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 25))
    assert.equal(billingLog.filter(item => item.type === 'charge').length, chargeCount + 1)
    await evaluate("localStorage.setItem('lawverify-cloud-token', 'qa-switched-session')")
    while (billingLog.at(-1).type !== 'refund' && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 25))
    assert.equal(billingLog.at(-1).type, 'refund')
    assert.equal(billingLog.at(-1).headers.authorization, 'Bearer ' + originalToken, '退款必须使用原扣费账号凭据')
    assert.equal(documentMock.requests.length, requestCount, '会话变化后不能发起生成请求')
  } finally {
    await evaluate('localStorage.setItem("lawverify-cloud-token", ' + JSON.stringify(originalToken) + ')')
    setBillingDelay(0)
  }
  await wait("document.querySelector('.new-error')?.textContent.includes('会话')")
  await clickText('.new-error button', '关闭')
  await clickText('.workbench-assistant-tabs [role=tab]', '联动依据')
  console.log('PASS document generation, model/evidence selection, save-before-rewrite, stop draft and refunds')
}
