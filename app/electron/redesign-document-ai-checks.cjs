const assert = require('node:assert/strict')

module.exports = async function checkDocumentAI({ evaluate, wait, clickText, selectDocumentText, fill, screenshot, saved, writeWorkspace, reload, enter, documentMock, billingLog, setBillingDelay, window }) {
  const previousPosition = await saved(async state => {
    const folder = state.cases.find(item => item.id === 'qa-case')
    const previousPosition = folder.agent?.position
    folder.agent = { ...folder.agent, position: { party: '王某', role: 'plaintiff', version: 1, confirmedAt: new Date().toISOString(), goals: [], admissions: [], disputes: [], boundaries: [] } }
    state.aiBillingMode = 'client'
    await writeWorkspace(state)
    return previousPosition
  })
  await reload()
  const caseName = await saved(state => state.cases.find(item => item.id === 'qa-case').name)
  await enter(caseName)
  await clickText('.workspace-doc-strip button', 'AI 助手')
  await wait("document.querySelector('.workspace-ai-modes')")
  const moreLabel = () => evaluate("document.querySelector('.workspace-ai-more').getAttribute('aria-label')")
  const equalCards = () => evaluate(`(() => {
    const cards = [...document.querySelectorAll('.workspace-ai-modes > button[aria-pressed]')].map(button => button.getBoundingClientRect());
    return cards.length === 4 && cards.every(box => Math.abs(box.width - cards[0].width) < 1
      && Math.abs(box.height - cards[0].height) < 1 && box.top === cards[0].top);
  })()`)
  assert.equal(await moreLabel(), '更多技能')
  assert.equal(await equalCards(), true)
  assert.equal(await evaluate("document.querySelector('.assistant-composer strong').textContent"), '自动路由')
  await screenshot('assistant-modes-default')
  const moreItem = '.workspace-ai-menu [role^=menuitem]'
  const openMore = async () => {
    await evaluate("document.querySelector('.workspace-ai-more').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,button:0,pointerType:'mouse'}))")
    await wait("document.querySelector('.workspace-ai-menu [role^=menuitem]')")
  }
  await openMore()
  assert.equal(await evaluate("document.querySelector('.workspace-ai-menu [aria-checked=true]')"), null)
  await clickText(moreItem, '风险与补强')
  assert.equal(await moreLabel(), '风险与补强，更多技能')
  assert.equal(await evaluate("document.querySelector('.assistant-composer strong').textContent"), '风险与补强')
  assert.equal(await evaluate("document.querySelector('.workspace-ai-more').hasAttribute('data-active')"), true)
  await openMore()
  await wait("document.activeElement?.getAttribute('aria-label') === '风险与补强'")
  assert.equal(await evaluate("document.activeElement.getAttribute('aria-checked')"), 'true')
  await clickText(moreItem, '风险与补强')
  await clickText('.workspace-ai-modes button', '案例报告')
  assert.equal(await moreLabel(), '更多技能')
  assert.equal(await evaluate("document.querySelector('.assistant-composer strong').textContent"), '案例报告')
  const [desktopWidth, desktopHeight] = window.getSize()
  window.setSize(390, 900)
  await wait('window.innerWidth <= 400')
  assert.equal(await equalCards(), true)
  await screenshot('assistant-modes-390')
  window.setSize(desktopWidth, desktopHeight)
  await wait('window.innerWidth > 880')
  await clickText('.workspace-ai-modes button', '案例报告')
  await openMore()
  await clickText(moreItem, '风险与补强')
  await openMore()
  await wait("document.activeElement?.getAttribute('aria-label') === '风险与补强'")
  assert.equal(await evaluate("document.querySelectorAll('.workspace-ai-menu [aria-checked=true]').length"), 1)
  await wait(`(() => {
    const menu = document.querySelector('.workspace-ai-menu').getBoundingClientRect();
    const item = document.activeElement.getBoundingClientRect();
    return item.top >= menu.top - 1 && item.bottom <= menu.bottom + 1;
  })()`)
  await screenshot('assistant-more-selected')
  await clickText(moreItem, '风险与补强')
  assert.equal(await moreLabel(), '更多技能')
  assert.equal(await evaluate("document.querySelector('.assistant-composer strong').textContent"), '自动路由')
  assert.equal(await evaluate("document.querySelector('.workspace-ai-more').hasAttribute('data-active')"), false)
  await clickText('.workspace-ai-modes button', '起草文书')
  await wait("document.querySelector('.assistant-composer textarea')")
  assert.doesNotMatch(await evaluate("document.querySelector('.workspace-ai-panel').textContent"), /语音|默认模型|本次使用的材料/)
  const send = () => clickText('.assistant-composer button', '发送')
  await fill('#workspace-ai-prompt', '起草民事起诉状')
  documentMock.setScenario('success')
  const startCharges = billingLog.filter(item => item.type === 'charge').length
  const pressEnter = (options = {}) => evaluate(`document.querySelector('#workspace-ai-prompt').dispatchEvent(new KeyboardEvent('keydown',${JSON.stringify({ key: 'Enter', bubbles: true, cancelable: true, ...options })}))`)
  assert.equal(await pressEnter({ isComposing: true }), true, '输入法确认应保留默认行为')
  assert.equal(await pressEnter({ shiftKey: true }), true, 'Shift+Enter 应保留换行')
  assert.equal(billingLog.filter(item => item.type === 'charge').length, startCharges)
  assert.equal(await pressEnter(), false, '普通 Enter 提交流式起草并阻止默认换行')
  await wait("document.querySelector('.document-generated-preview')?.textContent.includes('采纳并保存草稿')")
  await saved(state => assert.equal(state.certificates.some(item => item.title === '回归AI起草文书'), false))
  await clickText('.document-generated-preview button', '放弃候选')
  await wait("!document.querySelector('.document-generated-preview')")
  await saved(state => assert.equal(state.certificates.some(item => item.title === '回归AI起草文书'), false))
  await fill('#workspace-ai-prompt', '起草民事起诉状')
  await send()
  await wait("document.querySelector('.document-generated-preview')?.textContent.includes('采纳并保存草稿')")
  await clickText('.document-generated-preview button', '采纳并保存草稿')
  await wait("document.querySelector('.ctool h1')?.textContent === '回归AI起草文书' && document.querySelector('.whole-document-content[contenteditable=false]')")
  const generated = await saved(state => state.certificates.find(item => item.title === '回归AI起草文书'))
  assert.match(generated.paragraphs[0].text, /AI起草正文/)
  assert.deepEqual(documentMock.requests.at(-1).payload.evidenceIds, ['qa-evidence'])
  assert.equal(documentMock.requests.at(-1).payload.model, undefined)
  assert.equal(billingLog.filter(item => item.type === 'charge').length, startCharges + 2)
  await clickText('.workspace-ai-header button', '关闭 AI 助手')
  await wait("!document.querySelector('.workspace-ai-panel')")
  await selectDocumentText(generated.paragraphs[0].text)
  await wait("Array.from(document.querySelectorAll('.workspace-doc-strip button')).some(button => button.textContent.trim() === '问 AI')")
  await clickText('.workspace-doc-strip button', '问 AI')
  await wait("document.querySelector('.workspace-ai-quote')")
  await openMore()
  await clickText(moreItem, '改写润色')
  await fill('#workspace-ai-prompt', '补充论证并优化表达')
  await send()
  await wait("document.querySelector('.document-generated-preview')?.textContent.includes('经核对，AI起草正文')")
  await saved(state => assert.equal(state.certificates.find(item => item.id === generated.id).paragraphs[0].text, generated.paragraphs[0].text))
  await clickText('.document-assistant-actions button', '采纳并替换选区')
  await wait("document.querySelector('.document-assistant [role=status]')?.textContent.includes('已采纳选区改写')")
  await saved(state => assert.equal(state.certificates.find(item => item.id === generated.id).paragraphs[0].aiOrigin, 'rewrite'))
  await screenshot('document-ai')
  await clickText('.workspace-ai-modes button', '起草文书')
  documentMock.setScenario('interrupt')
  await fill('#workspace-ai-prompt', '再次调整表述')
  await send()
  await wait("document.querySelector('.document-generated-preview')?.textContent.includes('中断前已经生成')")
  assert.equal(await evaluate("Array.from(document.querySelectorAll('.workspace-ai-modes button')).every(button=>button.disabled)"), true)
  await selectDocumentText()
  await evaluate("new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))")
  assert.ok(await evaluate("Boolean(document.querySelector('.document-assistant'))"), '生成期间收到正文选区应保持助手挂载')
  await clickText('.workspace-ai-header button', '关闭 AI 助手')
  await wait("!document.querySelector('.workspace-ai-panel')")
  await wait("Array.from(document.querySelectorAll('.workspace-doc-strip button')).some(button=>button.textContent.trim()==='AI 助手'&&!button.disabled)")
  await saved(state => assert.ok(!state.certificates.some(item => item.paragraphs.some(paragraph => paragraph.text.includes('中断前已经生成')))))
  assert.ok(billingLog.some(item => item.type === 'refund'))
  await clickText('.workspace-doc-strip button', 'AI 助手')
  await wait("document.querySelector('.assistant-composer textarea')")
  await clickText('.workspace-ai-modes button', '起草文书')
  documentMock.setScenario('failure')
  await fill('#workspace-ai-prompt', '失败回归')
  const refunds = billingLog.filter(item => item.type === 'refund').length
  await send()
  await wait("document.querySelector('.new-error')?.textContent.includes('模拟模型生成失败')")
  assert.equal(billingLog.filter(item => item.type === 'refund').length, refunds + 1)
  await clickText('.new-error button', '关闭')
  documentMock.setScenario('success')
  const requestCount = documentMock.requests.length
  const chargeCount = billingLog.filter(item => item.type === 'charge').length
  const originalToken = await evaluate("localStorage.getItem('lawverify-cloud-token')")
  setBillingDelay(600)
  try {
    await fill('#workspace-ai-prompt', '扣费期间会话变化回归')
    await send()
    const deadline = Date.now() + 10000
    while (billingLog.filter(item => item.type === 'charge').length === chargeCount && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 25))
    assert.equal(billingLog.filter(item => item.type === 'charge').length, chargeCount + 1)
    await evaluate("localStorage.setItem('lawverify-cloud-token', 'qa-switched-session')")
    while (billingLog.at(-1).type !== 'refund' && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 25))
    assert.equal(billingLog.at(-1).type, 'refund')
    assert.equal(billingLog.at(-1).headers.authorization, 'Bearer ' + originalToken, '退款必须使用原扣费账号凭据')
    assert.equal(documentMock.requests.length, requestCount, '会话变化后不能发起生成请求')
  } finally {
    await evaluate('localStorage.setItem("lawverify-cloud-token", ' + JSON.stringify(originalToken) + ')')
    setBillingDelay(0)
  }
  await wait("document.querySelector('.new-error')?.textContent.includes('会话')")
  await clickText('.new-error button', '关闭')
  await clickText('.workspace-ai-header button', '关闭 AI 助手')
  await saved(async state => {
    state.cases.find(item => item.id === 'qa-case').agent.position = previousPosition
    await writeWorkspace(state)
  })
  console.log('PASS document generation, scoped rewrite preview and adoption, cancellation and refunds')
}
