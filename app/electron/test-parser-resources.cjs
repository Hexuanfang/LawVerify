const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { prepareParserResources } = require('./parser-resources.cjs')

const project = path.resolve(__dirname, '../..')
test('解析打包校验运行环境架构，并将脚本、模型与运行环境放入独立目录', () => {
  const directory = fs.mkdtempSync(path.join(project, 'tmp/parser-package-'))
  const source = path.join(directory, 'server')
  const runtime = path.join(source, 'python/.runtime')
  const models = path.join(source, 'python/.models')
  const executable = process.platform === 'win32' ? 'python.exe' : 'bin/python3'
  fs.mkdirSync(path.dirname(path.join(runtime, executable)), { recursive: true })
  fs.writeFileSync(path.join(runtime, executable), 'fixture')
  fs.mkdirSync(path.join(models, 'models/MinerU-4_models_onnx'), { recursive: true })
  fs.writeFileSync(path.join(source, 'python/worker.py'), '# fixture')
  fs.writeFileSync(path.join(runtime, 'lawverify-runtime.json'), JSON.stringify({ platform: process.platform, architecture: process.arch }))
  const target = path.join(directory, 'packaged')
  prepareParserResources(source, target)
  assert.ok(fs.existsSync(path.join(target, 'python/worker.py')))
  assert.ok(fs.existsSync(path.join(target, 'python-runtime', executable)))
  assert.ok(fs.existsSync(path.join(target, 'mineru-home/models/MinerU-4_models_onnx')))
  assert.ok(!fs.existsSync(path.join(target, 'python/.runtime')))
  assert.throws(() => prepareParserResources(source, path.join(directory, 'wrong'), { arch: process.arch === 'x64' ? 'arm64' : 'x64' }), /架构/)
})
