const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { prepareParserResources } = require('./parser-resources.cjs')

const project = path.resolve(__dirname, '../..')
test('解析打包校验运行环境架构，并将脚本、模型与运行环境放入独立目录', () => {
  const directory = fs.mkdtempSync(path.join(project, 'tmp/parser-package-'))
  const source = path.join(directory, 'server')
  const runtime = path.join(directory, 'tmp/parser-runtime')
  const workerRoot = path.join(directory, 'python-workers')
  const models = path.join(workerRoot, 'mineru-home')
  const executable = process.platform === 'win32' ? 'python.exe' : 'bin/python3'
  fs.mkdirSync(path.dirname(path.join(runtime, executable)), { recursive: true })
  fs.writeFileSync(path.join(runtime, executable), 'fixture')
  fs.mkdirSync(path.join(models, 'models/MinerU-4_models_onnx'), { recursive: true })
  fs.writeFileSync(path.join(workerRoot, 'worker.py'), '# fixture')
  fs.writeFileSync(path.join(workerRoot, 'http-worker-pool.mjs'), 'export {}')
  fs.writeFileSync(path.join(workerRoot, 'desktop-resources.mjs'), 'export {}')
  fs.writeFileSync(path.join(workerRoot, 'python-workers.ts'), 'export {}')
  fs.writeFileSync(path.join(runtime, 'lawverify-runtime.json'), JSON.stringify({ platform: process.platform, architecture: process.arch }))
  const target = path.join(directory, 'packaged')
  prepareParserResources(source, target)
  assert.ok(fs.existsSync(path.join(target, 'python/worker.py')))
  assert.ok(fs.existsSync(path.join(target, 'python-runtime', executable)))
  assert.ok(fs.existsSync(path.join(target, 'mineru-home/models/MinerU-4_models_onnx')))
  assert.ok(!fs.existsSync(path.join(target, 'python/mineru-home')))
  assert.ok(!fs.existsSync(path.join(target, 'python/.runtime')))
  assert.throws(() => prepareParserResources(source, path.join(directory, 'wrong'), { arch: process.arch === 'x64' ? 'arm64' : 'x64' }), /架构/)
})

test('按需模式生成固定清单和独立资源包，安装目录只保留脚本', { skip: process.platform !== 'win32' }, () => {
  const directory = fs.mkdtempSync(path.join(project, 'tmp/parser-download-package-'))
  const source = path.join(directory, 'server')
  const runtime = path.join(directory, 'tmp/parser-runtime')
  const models = path.join(source, 'python/.models/models/MinerU-4_models_onnx')
  fs.mkdirSync(runtime, { recursive: true })
  fs.mkdirSync(models, { recursive: true })
  fs.writeFileSync(path.join(runtime, 'python.exe'), 'fixture')
  fs.writeFileSync(path.join(runtime, 'lawverify-runtime.json'), JSON.stringify({ platform: process.platform, architecture: process.arch }))
  fs.mkdirSync(path.join(runtime, 'Lib/__pycache__'), { recursive: true })
  fs.writeFileSync(path.join(runtime, 'Lib/__pycache__/unused.pyc'), 'cache')
  fs.writeFileSync(path.join(models, 'model.onnx'), 'model')
  fs.writeFileSync(path.join(source, 'python/worker.py'), '# fixture')
  const target = path.join(directory, 'packaged')
  const outputDirectory = path.join(directory, 'release/parser-resources')
  prepareParserResources(source, target, { mode: 'download', outputDirectory, baseUrl: 'https://lawverify.zhijing.fun' })
  const manifest = JSON.parse(fs.readFileSync(path.join(target, 'parser-resource.json'), 'utf8'))
  assert.match(manifest.sha256, /^[a-f0-9]{64}$/)
  assert.equal(manifest.platform, 'win32')
  assert.equal(manifest.arch, process.arch)
  assert.equal(manifest.url, `https://lawverify.zhijing.fun/api/web/parser-resources/${manifest.sha256}.tar.gz`)
  assert.equal(fs.statSync(path.join(outputDirectory, `${manifest.sha256}.tar.gz`)).size, manifest.size)
  assert.ok(fs.existsSync(path.join(target, 'python/worker.py')))
  assert.ok(!fs.existsSync(path.join(target, 'python-runtime')))
  assert.ok(!fs.existsSync(path.join(target, 'mineru-home')))
  const { execFileSync } = require('node:child_process')
  const listing = execFileSync('tar', ['-tzf', path.join(outputDirectory, `${manifest.sha256}.tar.gz`)], { encoding: 'utf8' })
  assert.match(listing, /python-runtime\/python.exe/)
  assert.ok(!listing.includes('__pycache__'))
  const nextTarget = path.join(directory, 'packaged-again')
  fs.utimesSync(path.join(runtime, 'python.exe'), new Date(), new Date(Date.now() + 5000))
  prepareParserResources(source, nextTarget, { mode: 'download', outputDirectory })
  const nextManifest = JSON.parse(fs.readFileSync(path.join(nextTarget, 'parser-resource.json'), 'utf8'))
  assert.equal(nextManifest.sha256, manifest.sha256, '相同资源内容在重新构建时应复用相同资源包')
})
